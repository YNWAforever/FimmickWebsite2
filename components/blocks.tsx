export function IndustryMapBlock({ locale, ids }: { locale: Locale; ids?: IndustryId[] }) {
  const en = locale === "en";
  const list = ids ? ids.map(industryById) : industries;
  const views: IndustryView[] = list.map((i) => {
    const evidenceCase = cases.find((c) => c.industries.includes(i.id) && c.kind === "client-work");
    return {
      id: i.id,
      name: tr(i.name, locale),
      short: i.products.map((p) => productById(p).name).join(" · "),
      problem: tr(i.problem, locale),
      journey: i.journey.map((j) => ({ step: tr(j.step, locale), copy: tr(j.copy, locale), human: !!j.human, who: j.human ? (en ? "Your team decides" : "由你的團隊決定") : j.product ? productById(j.product).name : "" })),
      products: i.products.map((p) => ({ label: productById(p).name, href: href(locale, paths.product(p)) })),
      services: i.services.map((s) => ({ label: tr(serviceById(s).name, locale), href: href(locale, paths.service(s)) })),
      evidence: evidenceCase ? { label: tr(evidenceCase.title, locale), href: href(locale, paths.case(evidenceCase.slug)), kind: tr(caseKindLabel[evidenceCase.kind], locale) } : undefined,
      proof: tr(i.proof, locale),
      output: tr(i.output, locale),
      cta: { label: en ? `Discuss ${tr(i.name, locale)}` : `討論${tr(i.name, locale)}方案`, href: href(locale, paths.contact({ intent: "configuration", industry: i.id })) },
      detail: { label: en ? "Full industry page" : "查看完整行業頁面", href: href(locale, paths.industry(i.id)) },
    };
  });
  return <IndustryMap industries={views} labels={en ? { group: "Choose a sector", products: "Products", services: "Services", evidence: "Evidence", output: "Output", noEvidence: "No published case for this sector yet — the workflow shown is a labelled example." } : { group: "選擇行業", products: "產品", services: "服務", evidence: "證據", output: "成果", noEvidence: "此行業暫未有公開案例——所示流程為已標示的示例。" }} />;
}

