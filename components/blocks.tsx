export function ExampleTabs({ locale, initial = "content" }: { locale: Locale; initial?: ExampleId }) {
  const bundle: ExampleBundle = {
    intelligence: exampleData(locale, "intelligence"),
    content: exampleData(locale, "content"),
    "follow-up": exampleData(locale, "follow-up"),
    "website-ops": exampleData(locale, "website-ops"),
  };
  const tabs = (["intelligence", "content", "follow-up", "website-ops"] as const).map((id) => ({
    id,
    label: tr(solutionById(ex.exampleMeta[id].solution).short, locale),
    hint: ex.exampleMeta[id].products.map((p) => productById(p).name).join(" · "),
  }));
  return <ExampleViewer bundle={bundle} tabs={tabs} initial={initial} label={locale === "en" ? "Choose an example" : "選擇示例"} />;
}

export function ExampleBlock({ locale, id }: { locale: Locale; id: ExampleId }) {
  switch (id) {
    case "intelligence":
      return <SingleExample id="intelligence" data={exampleData(locale, "intelligence")} />;
    case "content":
      return <SingleExample id="content" data={exampleData(locale, "content")} />;
    case "follow-up":
      return <SingleExample id="follow-up" data={exampleData(locale, "follow-up")} />;
    default:
      return <SingleExample id="website-ops" data={exampleData(locale, "website-ops")} />;
  }
}

