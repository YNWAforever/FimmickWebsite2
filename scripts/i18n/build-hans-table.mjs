#!/usr/bin/env node
/**
 * Generate lib/hans-table.ts — the Traditional (Hong Kong) → Simplified
 * Chinese table used to render the /zh-hans pages from the zh-HK copy.
 *
 *   npm run i18n:hans          # regenerate after changing Chinese copy
 *   npm run i18n:hans -- --check   # exit 1 if the committed table is stale
 *
 * The table covers every CJK character that appears in the site source
 * (app, components, lib, content — not the preserved legacy archive, which
 * already has native Simplified articles). Conversion uses OpenCC (hk → cn)
 * character by character, plus a short phrase list for cases where a
 * character's Simplified form depends on the word. The same table runs on
 * the server and in the browser, so rendering is identical on both.
 *
 * This is machine conversion. Mainland vocabulary is not substituted
 * (e.g. 電郵 → 电邮, not 邮件); a native reviewer should check the output
 * before release (see docs/redesign/release-runbook.md, B3).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as OpenCC from "opencc-js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const out = path.join(root, "lib/hans-table.ts");
const convert = OpenCC.Converter({ from: "hk", to: "cn" });

/** Words whose Simplified form differs from character-by-character conversion. */
const phrases = [
  // 著 is simplified to 着 except in these words, where 著 is retained.
  ["著名", "著名"], ["顯著", "显著"], ["著作", "著作"], ["名著", "名著"], ["原著", "原著"], ["土著", "土著"], ["編著", "编著"], ["論著", "论著"], ["專著", "专著"],
  ["甚麼", "什么"],
  // 覆 → 复 in these words (覆 is kept in 覆蓋 etc.).
  ["回覆", "回复"], ["反覆", "反复"], ["答覆", "答复"],
];
const charOverrides = { "著": "着" };

function walk(dir, list = []) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (name === "node_modules" || name === ".next" || name === "legacy") continue;
    const stat = fs.statSync(full);
    if (stat.isDirectory()) walk(full, list);
    else if (/\.(ts|tsx)$/.test(name) && !full.endsWith("hans-table.ts")) list.push(full);
  }
  return list;
}

const chars = new Set();
for (const dir of ["app", "components", "lib", "content"]) {
  for (const file of walk(path.join(root, dir))) {
    for (const ch of fs.readFileSync(file, "utf8").match(/[㐀-鿿豈-﫿]/g) ?? []) chars.add(ch);
  }
}

const pairs = [];
for (const ch of [...chars].sort()) {
  const simplified = charOverrides[ch] ?? convert(ch);
  if (simplified !== ch && [...simplified].length === 1) pairs.push(ch + simplified);
}

const body = `// Generated by scripts/i18n/build-hans-table.mjs — do not edit by hand.
// Traditional → Simplified pairs for every CJK character used in the site source.
export const hansPairs = ${JSON.stringify(pairs.join(""))};
export const hansPhrases: [string, string][] = ${JSON.stringify(phrases)};
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== body) {
    console.error("lib/hans-table.ts is out of date. Run: npm run i18n:hans");
    process.exit(1);
  }
  console.log(`hans table up to date (${pairs.length} characters)`);
} else {
  fs.writeFileSync(out, body);
  console.log(`wrote ${path.relative(root, out)}: ${pairs.length} character pairs, ${phrases.length} phrases`);
}
